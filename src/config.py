"""Пороги, веса и размер выдачи — в одном месте.

Здесь собраны только числа-гипотезы: те, которые предполагается проверять
и менять по результатам анализа накопленных прогонов. В разделе 9 spec.md
таблица `runs` хранит `config_json` каждого прогона — именно этот объект
туда и ляжет, поэтому все параметры должны быть в одном сериализуемом месте.

Соглашения, менять которые не предполагается — таймфрейм, длина базового
окна, медиана вместо среднего, — живут в candles.py и metrics.py. У них
другая природа: это не подбираемые параметры, а зафиксированные решения.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ExchangeFilters:
    """Пороги отсева одной биржи, раздел 5 spec.md.

    Неравенства строгие: значение ровно на пороге проходит фильтр.

    Пороги вынесены по биржам, потому что различия между ними реальны:
    статус активных торгов у Binance называется TRADING, у OKX — live,
    а числа сделок за 24 часа OKX в публичном API не отдаёт вовсе,
    поэтому у него этот фильтр отключён (None).
    """

    active_status: str = "TRADING"
    min_quote_volume_24h: float = 50_000_000  # USDT за 24 часа
    min_trades_24h: int | None = 10_000


BINANCE_FILTERS = ExchangeFilters()

# Порог оборота тот же, что у Binance: проскальзывание зависит от абсолютной
# глубины рынка, а не от места биржи в рейтинге. Измерено — при 50 млн на OKX
# остаётся 29 инструментов, отбирать есть из чего.
OKX_FILTERS = ExchangeFilters(active_status="live", min_trades_24h=None)


@dataclass(frozen=True)
class Config:
    """Параметры одного прогона.

    frozen=True специально: конфиг прогона не должен меняться по ходу дела,
    иначе сохранённый config_json перестанет соответствовать тому, как
    результат на самом деле получен.
    """

    filters: dict[str, ExchangeFilters] = field(
        default_factory=lambda: {"BINANCE": BINANCE_FILTERS, "OKX": OKX_FILTERS}
    )

    # --- Пороги интереса, раздел 6 spec.md ---
    # Неравенства нестрогие: значение ровно на пороге считается сработавшим.
    rvol_threshold: float = 3.0
    rtc_threshold: float = 2.5
    ve_threshold: float = 2.0

    # --- Скоринг, раздел 7 spec.md ---
    # Веса в сумме дают 1.0, поэтому инструмент, у которого все три метрики
    # ровно на порогах, получает score ровно 1.0. Это делает шкалу читаемой:
    # score выше единицы означает «сильнее, чем минимально интересно».
    rvol_weight: float = 0.4
    rtc_weight: float = 0.3
    ve_weight: float = 0.3

    # Потолок нормированной метрики: один экстремальный выброс не должен
    # перекрывать вклад остальных двух.
    score_cap: float = 3.0

    # Сколько метрик из трёх должно сработать, чтобы инструмент стал
    # кандидатом. Защита от разовой аномалии в одном показателе.
    min_triggered_metrics: int = 2

    top_n: int = 15


DEFAULT = Config()
